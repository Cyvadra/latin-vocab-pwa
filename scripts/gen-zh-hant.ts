// Generates src/lib/zh-hant.generated.ts (Traditional Chinese UI strings + guide) from the simplified sources.
import fs from "node:fs";
import path from "node:path";
import { CONTENT } from "../src/lib/guide-content";
import { zh } from "../src/lib/strings";
import { convertDeep } from "./zh-convert";

const out = `// GENERATED by scripts/gen-zh-hant.ts from strings.ts and guide-content.ts. Do not edit.
import type { StringKey } from "./strings";
import type { Block } from "./guide-content";

export const strings: Record<StringKey, string> = ${JSON.stringify(convertDeep(zh), null, 2)};

export const guide: { title: string; back: string; blocks: Block[] } = ${JSON.stringify(convertDeep(CONTENT.zh), null, 2)};
`;
fs.writeFileSync(path.resolve(__dirname, "..", "src", "lib", "zh-hant.generated.ts"), out);
console.log("Wrote src/lib/zh-hant.generated.ts");
